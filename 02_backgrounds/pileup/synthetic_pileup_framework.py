HITS_PER_LAYER_AT_MU50 = 1000  # paper's own stated O(1000)/layer at mu~50 (Sec IV)


def generate_synthetic_pileup_hits(mu, rng, n_layers_total=8):
    """
    SYNTHETIC PLACEHOLDER ONLY (see module docstring) -- generates random,
    mutually uncorrelated hits per layer, uniformly in phi and in z (then
    filtered to the same |eta|<1.8 fiducial range the real detector-response
    pipeline uses), scaled linearly with mu toward the paper's stated
    O(1000) hits/layer at mu~50. This is a crude, explicitly-labeled proxy
    for "pile-up tracks for which reconstruction failed" -- NOT a
    physically simulated pile-up sample.

    Returns hits_by_layer: {layer_idx: [(x,y,z), ...]}
    """
    n_per_layer = int(round(HITS_PER_LAYER_AT_MU50 * mu / 50.0))
    hits_by_layer = {k: [] for k in range(1, n_layers_total + 1)}
    if n_per_layer <= 0:
        return hits_by_layer
    for layer in LAYERS:
        idx = {"L1_IBL": 1, "L2_PixelB0": 2, "L3_PixelB1": 3, "L4_PixelB2": 4,
               "L5_SCT_B3": 5, "L6_SCT_B4": 6, "L7_SCT_B5": 7, "L8_SCT_B6": 8}[layer["name"]]
        r = layer["r_cm"]
        # Draw z from a range wide enough that the eta cut does the real
        # filtering (matches how the real pipeline restricts to the barrel).
        z_range_cm = r / np.tan(2 * np.arctan(np.exp(-FIDUCIAL_ETA_MAX))) * 1.5
        n_kept = 0
        attempts = 0
        while n_kept < n_per_layer and attempts < n_per_layer * 5:
            attempts += 1
            phi = rng.uniform(-np.pi, np.pi)
            z = rng.uniform(-z_range_cm, z_range_cm)
            eta = eta_from_theta(np.arctan2(r, z))
            if abs(eta) > FIDUCIAL_ETA_MAX:
                continue
            x, y = r * np.cos(phi), r * np.sin(phi)
            hits_by_layer[idx].append((x, y, z))
            n_kept += 1
    return hits_by_layer


def overlay_and_reconstruct(hard_hits_by_layer, pileup_hits_by_layer, vertex_cm):
    """
    Combine hard-event hits (already vertex-relative, i.e. the caller has
    ALREADY applied vertex_relative_hits to them) with synthetic pile-up
    hits (generated directly in the lab/global frame above, so vertex-shift
    them here the SAME way, using the SAME vertex, for consistency with the
    signal pipeline) and run the UNCHANGED Sec III C / IV algorithm on the
    combined set. No cut or algorithm logic is touched here.
    """
    combined = {k: list(hard_hits_by_layer.get(k, [])) for k in range(1, 9)}
    for k, hits in pileup_hits_by_layer.items():
        shifted = [tuple(vertex_relative_hits([h], vertex_cm)[0]) for h in hits]
        combined[k].extend(shifted)
    candidates = seeding_and_iterative_fit(combined)
    winner = apply_signal_region_cuts(candidates)
    return combined, candidates, winner


