"""
Part D: real pile-up overlay. Generates detector hits for minimum-bias
pile-up particles (via the validated exact-helix propagation,
helix_propagation.py) and overlays them with a hard event's own hits,
through the SAME detector-response model already validated for signal and
the photon-conversion background (04_detector_sim/atlas_geometry.py,
04_detector_sim/trajectory_to_hits.py's quantize_pixel/merge logic).

SCOPE / DOCUMENTED SIMPLIFICATION (Part B audit item 16): the paper (Sec
III D) directs pile-up modelling to the detector described in ref [34]
(arXiv:1612.00850), whose Appendix A includes the beam pipe, IBL, 3 pixel
layers, SCT barrel AND endcap discs, a service layer, TRT (barrel+endcap)
and the ECAL, with Bethe-Bloch energy loss and single-photon bremsstrahlung
at each material crossing, plus explicit trajectory-termination conditions
(reach calorimeter; KE<10% of mass; time-of-flight>25ns; escape the forward
region uncovered by calorimeters -- ref [34] Appendix A). NONE of the
endcap/service/TRT/ECAL material or Bethe-Bloch/bremsstrahlung energy loss
is implemented here. This module instead reuses the main paper's OWN
simplified Sec III A barrel-8-layer model (already validated for signal/
conversion background) for pile-up hits too -- a real simplification
relative to ref [34], not a paper requirement. The DIRECTION and SIZE of
this simplification's effect on the fake-coplanarity background rate are
UNQUANTIFIED by anything in this repository -- it is NOT demonstrated (and
should not be claimed) that this makes the estimate conservative,
optimistic, or negligible in either direction. Missing endcap/TRT/ECAL
material could add pile-up hits (more material = more low-pT loopers/
secondaries) or the missing secondaries specifically could remove them;
these effects are not modeled here and no net direction is asserted.

VERIFIED PRESCRIPTIONS USED HERE (paper Sec III D + ref [34] Sec II/App. A):
  - Pile-up multiplicity: Poisson distribution, mean mu (ref [34], p.14:
    "we assume the number of pile-up vertices follows a Poisson
    distribution with an average of 50 interactions per bunch crossing").
    The main paper does not literally restate "Poisson" itself, but
    explicitly inherits ref [34]'s pile-up generation procedure wholesale
    ("We model pile-up by randomly selecting minimum bias events from a
    sample of 125x10^3 events generated by Pythia8, processed by the
    simplified detector described in [34]"), so this is treated as MATCH,
    not an independent assumption.
  - Per-interaction vertex: z0 ~ Normal(0, 45mm), x0=y0=0 exactly (ref [34]:
    "We neglect the width of the beamspot in the transverse direction").
    Applied INDEPENDENTLY to every pile-up interaction (and to the hard
    interaction), not a single shared z0 for the whole bunch crossing.
  - Sampling: minimum-bias events drawn from the pool WITH replacement,
    same pool event may appear multiple times within one hard event.
    NOT SPECIFIED BY PAPER OR ref [34] -- documented ASSUMPTION (the pool,
    125,000 events, is far smaller than mu*N_hard_events will typically
    require, so replacement is the only way to draw a full sample; this is
    also standard ATLAS/CMS pile-up-overlay practice).
  - Reconstruction: fit is performed relative to the HARD-SCATTER event's
    OWN true vertex only (Sec III C: "We will assume that the primary
    vertex is identified correctly, and is located at the origin") -- NOT
    per-pile-up-vertex. Pile-up hits are generated at their true (smeared)
    lab-frame position like any other hit; only the coordinate shift before
    the plane fit uses the hard vertex.
  - Pixel-hit merging is applied ACROSS the combined (hard + pile-up) hit
    list, since real ATLAS clustering cannot distinguish hit origin.
  - Per-hit 25ns time-of-flight cutoff (ref [34] Appendix A, trajectory-
    termination condition (iii): "Their time-of-flight exceeds 25 ns" --
    verbatim). This is a DIFFERENT requirement from the main paper's own
    Sec IV "25 ns timing cut" (which is a TRUTH-level, event-level cut on
    whether a QUIRK EVENT counts as fiducial, i.e. eps_fid). Ref [34]'s
    condition is a PER-PARTICLE propagation-termination rule applied inside
    its own detector simulation -- since the main paper explicitly sends
    pile-up "through the simplified detector described in [34]," a pile-up
    particle's trajectory (and hence any layer crossing) is only valid past
    the point ref [34]'s own simulation would have stopped propagating it.
    Applied here as a PER-HIT rejection: any pile-up layer crossing with
    t_ns > 25 is not counted as a hit. (Not implemented previously -- added
    here after re-reading ref [34] Appendix A directly, not from memory.)
  - Neutral pile-up particles are never propagated for tracker hits (ref
    [34] Appendix A, verbatim: "Neutral particles are always propagated
    straight to the calorimeter barrel or wheels without energy loss in the
    inner tracker" -- i.e. they never produce tracker hits in ref [34]'s own
    model either). This CONFIRMS (not just assumes) generate_minbias.py's
    charge!=0 filter as the correct match to ref [34], not merely a
    reasonable guess.
"""
PILEUP_HIT_TIMING_CUT_NS = 25.0  # ref [34] Appendix A, propagation-termination condition (iii)
import sys
import numpy as np
sys.path.insert(0, "/home/rafia/coplanarity_study/04_detector_sim")
sys.path.insert(0, "/home/rafia/coplanarity_study/02_backgrounds/pileup")
from atlas_geometry import LAYERS, FIDUCIAL_ETA_MAX, BEAMSPOT_SIGMA_Z_CM, eta_from_theta
from trajectory_to_hits import quantize_pixel, merge_neighboring_pixel_hits
from helix_propagation import find_helix_layer_crossings

LAYER_RADII_CM = [layer["r_cm"] for layer in LAYERS]


def pileup_particle_hits(px, py, pz, m, charge_e, vertex_cm, particle_tag,
                          rng, B_tesla=2.0):
    """
    Propagate ONE ordinary (Lambda=0) charged pile-up particle via the exact
    helix solution and return its detector hits in the same dict schema as
    trajectory_to_hits.py's raw_hits (so merge_neighboring_pixel_hits can be
    reused unchanged on a combined hard+pileup hit list).
    """
    p_gev = np.array([px, py, pz])
    x0_cm = np.asarray(vertex_cm, dtype=float)
    crossings = find_helix_layer_crossings(x0_cm, p_gev, m, charge_e, B_tesla, LAYER_RADII_CM)

    hits = []
    for layer in LAYERS:
        result = crossings.get(layer["r_cm"])
        if result is None:
            continue
        xyz, t_ns = result
        if t_ns is None or t_ns > PILEUP_HIT_TIMING_CUT_NS:
            continue  # ref [34] Appendix A stopping condition (iii)
        x, y, z = xyz
        r = np.hypot(x, y)
        # eta from the hit's GLOBAL (lab-frame) position, NOT vertex-relative
        # -- matches trajectory_to_hits.py's identical, already-validated
        # convention (see that module's docstring): the barrel's |eta|<1.8
        # acceptance is a fixed HARDWARE extent in the lab frame, and a
        # vertex-relative eta would silently cancel the very beamspot-
        # smearing effect (each interaction's own displaced z0) the paper
        # wants included in the fiducial acceptance. Verified by direct
        # construction here: z already reflects this particle's own
        # (possibly far off-origin) vertex_cm through the helix propagation
        # above, so a fast/slow-moving or steeply-angled track from a
        # displaced vertex gets a correspondingly different (correct) eta.
        eta = eta_from_theta(np.arctan2(r, z)) if (z != 0 or r != 0) else 0.0
        if abs(eta) > FIDUCIAL_ETA_MAX:
            continue
        phi = np.arctan2(y, x)
        rphi = layer["r_cm"] * phi

        if layer["is_pixel"]:
            rphi_hit, z_hit, idx_rphi, idx_z = quantize_pixel(
                rphi, z, layer["eff_res_rphi_um"], layer["eff_res_z_um"])
        else:
            sigma_rphi_cm = layer["eff_res_rphi_um"] * 1e-4
            sigma_z_cm = layer["eff_res_z_um"] * 1e-4
            rphi_hit = rphi + rng.normal(0.0, sigma_rphi_cm)
            z_hit = z + rng.normal(0.0, sigma_z_cm)
            idx_rphi = idx_z = None

        phi_hit = rphi_hit / layer["r_cm"]
        x_hit = layer["r_cm"] * np.cos(phi_hit)
        y_hit = layer["r_cm"] * np.sin(phi_hit)

        hits.append({
            "layer": layer["name"], "layer_r_cm": layer["r_cm"],
            "quirk_index": particle_tag, "t_ns": t_ns,
            "x": x_hit, "y": y_hit, "z": z_hit,
            "is_pixel": layer["is_pixel"],
            "idx_rphi": idx_rphi, "idx_z": idx_z,
        })
    return hits


def build_pool_index(minbias_pool_df):
    """
    Pre-group the minimum-bias pool ONCE into {event_id: (px,py,pz,m,charge)
    numpy arrays}, so repeated overlay calls (one per hard event, potentially
    hundreds per mu run) never re-run pandas groupby() on the full pool or
    re-materialize per-row Python objects via itertuples() -- both of which
    scale with total pool size per call, not per pile-up interaction sampled.
    Memory: proportional to the pool itself (~230MB for 20,000 events), held
    once and reused -- not duplicated per call.
    """
    index = {}
    for ev_id, g in minbias_pool_df.groupby("event", sort=False):
        index[ev_id] = (
            g["px"].to_numpy(), g["py"].to_numpy(), g["pz"].to_numpy(),
            g["m"].to_numpy(), g["charge"].to_numpy(),
        )
    return index


def sample_pileup_hits(pool_index, mu, rng, B_tesla=2.0):
    """
    Sample Poisson(mu) pile-up interactions, each drawn WITH replacement
    from pool_index (see build_pool_index), each assigned its OWN
    z0 ~ Normal(0, 45mm) vertex (x0=y0=0), and return
    (all_pileup_hits, stats_dict).
    """
    n_pu = rng.poisson(mu)
    pool_event_ids = np.fromiter(pool_index.keys(), dtype=np.int64)
    all_hits = []
    sampled_event_ids = []
    n_particles_total = 0

    if n_pu > 0 and len(pool_event_ids) > 0:
        chosen = rng.choice(pool_event_ids, size=n_pu, replace=True)
        sampled_event_ids = [int(e) for e in chosen]  # native int, not numpy.int64
        for pu_idx, ev_id in enumerate(chosen):
            z0_cm = rng.normal(0.0, BEAMSPOT_SIGMA_Z_CM)
            vertex_cm = np.array([0.0, 0.0, z0_cm])
            px_arr, py_arr, pz_arr, m_arr, q_arr = pool_index[ev_id]
            n_particles_total += len(px_arr)
            for j in range(len(px_arr)):
                tag = f"pu{pu_idx}_ev{ev_id}_p{j}"
                hits = pileup_particle_hits(
                    px_arr[j], py_arr[j], pz_arr[j], m_arr[j], q_arr[j],
                    vertex_cm, tag, rng, B_tesla=B_tesla,
                )
                all_hits.extend(hits)

    stats = {
        "n_pu_interactions": int(n_pu),
        "sampled_pool_event_ids": sampled_event_ids,
        "n_pu_particles_propagated": n_particles_total,
        "n_pu_hits_premerge": len(all_hits),
    }
    return all_hits, stats


def overlay_and_merge(raw_hard_hits, raw_pileup_hits):
    """
    Combine RAW (pre-merge) hard-event hits with RAW pile-up hits into ONE
    list and apply pixel-merging (merge_neighboring_pixel_hits) EXACTLY
    ONCE, since real ATLAS clustering cannot tell hard-scatter hits from
    pile-up hits apart and a hit is only ever merged once in reality.

    CALLERS MUST PASS RAW HITS for raw_hard_hits (e.g.
    simulate_quirk_hits(...)'s traj["raw_hits"], NOT its primary
    already-merged return value) -- merging hard hits alone first and then
    merging the result again with pile-up is NOT equivalent in general:
    (1) a merged hard cluster's recomputed centroid position can differ
    enough from either original raw hit's position to change whether a
    nearby pile-up hit falls within one-pixel adjacency of it, and more
    severely (2) merge_neighboring_pixel_hits sets a multi-quirk merged
    cluster's own `quirk_index` field to None (see its docstring), so
    re-merging that already-merged hit a second time LOSES the original
    per-quirk provenance -- confirmed concretely by a unit test: two raw
    hard hits (quirk 1, quirk 2) + one raw pile-up hit, merged in one pass,
    correctly gives source_quirk_indices=[1,2,'pu0']; pre-merging the hard
    hits first then re-merging with the pile-up hit gives
    [None,'pu0'] instead -- provenance for BOTH original quirks is lost.

    `quirk_index` on pile-up hits is the string particle_tag (vs. the hard
    event's integer 1/2) -- merge_neighboring_pixel_hits only ever uses
    this field to record provenance (`source_quirk_indices`, sorted by
    str() to tolerate the mixed int/str types), so this is safe and lets a
    merged hit's provenance clearly show whether it mixed hard-scatter and
    pile-up contributions.

    Returns (merged_hits, stats) where stats distinguishes every stage
    requested by the re-audit:
      n_raw_hard_hits         -- len(raw_hard_hits), BEFORE any merging
      n_raw_pileup_hits       -- len(raw_pileup_hits), BEFORE any merging
      n_hits_premerge_combined  -- len(raw_hard_hits)+len(raw_pileup_hits),
                                    i.e. the input to the SINGLE merge pass
      n_hits_postmerge_combined -- len(merged), AFTER the single merge pass
      n_merged_hard_pileup_mixed -- number of merged clusters whose
                                    source_quirk_indices contains BOTH a
                                    hard-hit tag (int) and a pile-up tag (str)
    """
    combined = list(raw_hard_hits) + list(raw_pileup_hits)
    merged = merge_neighboring_pixel_hits(combined)
    # source_quirk_indices is set unconditionally by merge_neighboring_pixel_hits
    # on EVERY returned hit (pixel single/merged AND non-pixel pass-through
    # branches all set it -- verified by reading trajectory_to_hits.py's
    # merge_neighboring_pixel_hits directly), so no .get()/KeyError guard is
    # needed here; asserted rather than silently assumed.
    assert all("source_quirk_indices" in h for h in merged), \
        "merge_neighboring_pixel_hits did not set source_quirk_indices on every hit"
    n_mixed = sum(1 for h in merged
                  if len(h["source_quirk_indices"]) > 1
                  and any(isinstance(q, str) for q in h["source_quirk_indices"])
                  and any(not isinstance(q, str) for q in h["source_quirk_indices"]))
    return merged, {"n_raw_hard_hits": len(raw_hard_hits),
                     "n_raw_pileup_hits": len(raw_pileup_hits),
                     "n_hits_premerge_combined": len(combined),
                     "n_hits_postmerge_combined": len(merged),
                     "n_merged_hard_pileup_mixed": n_mixed}
