#!/usr/bin/env python3
"""07 R02 (2026-11-17): writes tables/R02_results_summary.md, all numbers of the 07 large-sample study in one place, read only from saved files
(tables/R01_*.csv, FIGURES_ROOT_2026-11-17/data/*.csv, signal/inputs_large/counts.csv, Stage 2 tables, test logs). No new physics; nothing is fitted.
Also writes tables/R02_integration_failures.csv (07 vs Stage 2 per channel and Lambda). Re-run after every R00_postprocess."""
import os, re, glob, datetime, numpy as np, pandas as pd
HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.abspath(f"{HERE}/.."); BASE = os.path.abspath(f"{R}/.."); T = f"{R}/tables"; D = f"{R}/FIGURES_ROOT_2026-11-17/data"
S2 = f"{BASE}/06_publication/S2_13p6TeV_run3_knapen_noPU_cop"; rd = pd.read_csv
out = []
def md(df, fmt=None):
    fmt = fmt or {}; cols = list(df.columns); L = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        L.append("| " + " | ".join((fmt[c](r[c]) if c in fmt and pd.notna(r[c]) else ("" if pd.isna(r[c]) else str(r[c]))) for c in cols) + " |")
    out.extend(L + [""])
def h(s): out.extend([s, ""])
f2 = lambda v: f"{v:.2f}"; f3 = lambda v: f"{v:.3f}"; f0 = lambda v: f"{v:.0f}"; g4 = lambda v: f"{v:.4g}"

G = rd(f"{T}/R01_N_grid_300fb.csv"); G2 = rd(f"{S2}/S2_N_grid_300fb.csv")
h(f"# 07 large-sample results summary (generated by reach/R02_results_summary.py, {datetime.date.today()})")
h("All numbers below are read from saved files; the source of each table is given in its heading. Luminosity 332 fb⁻¹ unless stated, √s = 13.6 TeV.")

# completeness
h("## 1. Grid completeness (tables/R01_N_grid_300fb.csv)")
c = G[G.sct == "Z0"].groupby(["channel", "status_with_f"]).size().unstack(fill_value=0).reset_index()
md(c); lam = sorted(G[G.status_with_f != "missing"].lambda_keV.unique()); lm = sorted(G[G.status_with_f == "missing"].lambda_keV.unique())
h(f"Λ values computed (keV): {', '.join(f'{x:g}' for x in lam)}." + (f" **Missing (band not yet propagated): {', '.join(f'{x:g}' for x in lm)} keV.**" if lm else " All bands complete."))

h("## 2. Samples: cross section, trigger, both charged (data/xsec_and_trigger.csv; 07 = 10k generated per point, Stage 2 = 2k)")
X = rd(f"{D}/xsec_and_trigger.csv")
a = X[X["sample"] == "07_10k"].set_index(["channel", "mass_gev"]); b = X[X["sample"] != "07_10k"].set_index(["channel", "mass_gev"])
t = a[["sigma_fb", "n_matched", "n_trigger", "eps_trig", "n_both_charged", "f_ch"]].copy()
t["eps_trig_stage2"] = b.eps_trig; t["f_ch_stage2"] = b.f_ch
t["pull_eps_trig"] = (a.eps_trig - b.eps_trig) / np.sqrt(((a.eps_trig_hi - a.eps_trig_lo) / 2) ** 2 + ((b.eps_trig_hi - b.eps_trig_lo) / 2) ** 2)
md(t.reset_index(), {"eps_trig": f3, "f_ch": f3, "eps_trig_stage2": f3, "f_ch_stage2": f3, "pull_eps_trig": f2, "sigma_fb": g4})
h(f"Largest |pull| of ε_trig between 07 and Stage 2: {t.pull_eps_trig.abs().max():.2f} (Wilson 68% half-widths added in quadrature).")

h("## 3. Quirk velocity β = |p|/E of the propagated quirks (data/beta_summary.csv)")
B = rd(f"{D}/beta_summary.csv")
md(B[["channel", "mass_gev", "n_events", "beta_p16", "beta_median", "beta_p84", "betaT_median", "betagamma_median", "frac_beta_lt_0p3", "frac_beta_gt_0p8"]],
   {c: f3 for c in ("beta_p16", "beta_median", "beta_p84", "betaT_median", "frac_beta_lt_0p3", "frac_beta_gt_0p8")} | {"betagamma_median": f2})

h("## 4. Efficiencies at Λ = 4 keV (tables/R01_N_grid_300fb.csv; Stage 2: S2_N_grid_300fb.csv)")
rows = []
for (ch, m), x in G[G.lambda_keV == 4.0].groupby(["channel", "mass_gev"]):
    if x.status_with_f.iloc[0] == "missing": continue
    y = G2[(G2.channel == ch) & (G2.mass_gev == m) & (G2.lambda_keV == 4.0)]
    r = dict(channel=ch, mass_gev=m, n_prop=int(x.n_prop.iloc[0]), eps_fid=x.n_fid.iloc[0] / x.n_prop.iloc[0], eps_fid_barrel_rule=x.n_fid_stage2.iloc[0] / x.n_prop.iloc[0])
    for s in ("Z0", "A580", "Z1160"): r[f"k/n {s}"] = x[x.sct == s].k.iloc[0] / x.n_prop.iloc[0]
    r["endcap share of k (A580)"] = x[x.sct == "A580"].k_endcap.iloc[0] / max(1, x[x.sct == "A580"].k.iloc[0])
    if len(y):
        r["eps_fid stage2"] = y.n_fid.iloc[0] / y.n_prop.iloc[0]
        for s in ("Z0", "Z1160"): r[f"k/n {s} stage2"] = y[y.sct == s].k.iloc[0] / y.n_prop.iloc[0]
    rows.append(r)
md(pd.DataFrame(rows), {c: f3 for c in pd.DataFrame(rows).columns if c not in ("channel", "mass_gev", "n_prop")})

h("## 5. Integration failures (simulate_quirk_hits: MIN_STEPS_PER_PERIOD not reached; counted as not fiducial, as in Stage 2)")
I = G[(G.sct == "Z0") & (G.status_with_f == "computed")].groupby(["channel", "lambda_keV"]).agg(n=("n_prop", "sum"), fail=("n_integration_fail", "sum")).reset_index()
I2 = G2[(G2.sct == "Z0") & (G2.status_with_f == "computed")].groupby(["channel", "lambda_keV"]).agg(n_s2=("n_prop", "sum"), fail_s2=("n_integration_fail", "sum")).reset_index()
I = I.merge(I2, on=["channel", "lambda_keV"], how="left"); I["rate"] = I.fail / I.n; I["rate_stage2"] = I.fail_s2 / I.n_s2
I.to_csv(f"{T}/R02_integration_failures.csv", index=False)
md(I, {"rate": lambda v: f"{100 * v:.2f}%", "rate_stage2": lambda v: f"{100 * v:.2f}%", "n_s2": f0, "fail_s2": f0})
h(f"Overall 07 rate: {100 * I.fail.sum() / I.n.sum():.2f}% ({int(I.fail.sum())} of {int(I.n.sum())} event-Λ pairs); Stage 2 on the same Λ: "
  f"{100 * I.fail_s2.sum() / I.n_s2.sum():.2f}%.")

h("## 6. Zero-background reach, 332 fb⁻¹ (tables/R01_reach.csv); Stage 2 = S2_reach.csv (barrel, 2k)")
RR = rd(f"{T}/R01_reach.csv")
for L in (332.0,):
    x = RR[RR.lumi_fb == L][["channel", "sct", "contour", "m_max_GeV", "m_max_lo", "m_max_hi", "at_lambda_keV", "m_max_stage2_GeV", "N_max_at_highest_mass_used", "reach_beyond_grid"]]
    md(x, {"m_max_stage2_GeV": f0})
x = RR[RR.reach_beyond_grid]
h("Rows with reach_beyond_grid = True (N ≥ threshold already at the highest grid mass, so the true reach is ≥ the grid edge and the quoted value is a lower bound): "
  + (", ".join(f"{r.channel} {r.sct} {r.lumi_fb:g} fb⁻¹ {r.contour}" for r in x.itertuples()) if len(x) else "none") + ".")
h("Other luminosities (300 and 355 fb⁻¹) are in tables/R01_reach.csv.")

h("## 7. Converted-photon background (tables/R01_background.csv; 332 fb⁻¹)")
BG = rd(f"{T}/R01_background.csv"); md(BG, {c: g4 for c in BG.columns if BG[c].dtype.kind == "f"})

h("## 8. Reach with background, 332 fb⁻¹ (tables/R01_reach_with_background.csv)")
RB = rd(f"{T}/R01_reach_with_background.csv"); x = RB[RB.lumi_fb == 332.0]
cols = [c for c in ("channel", "sct", "contour", "variant", "mu", "b_used", "N_bkg", "s_required", "m_max_GeV", "m_max_lo", "m_max_hi", "at_lambda_keV", "reach_beyond_grid") if c in x.columns]
md(x[cols].sort_values(["variant", "channel", "sct", "contour", "mu"]), {"b_used": f3, "N_bkg": f3, "s_required": f2})

h("## 9. Conversion probability from the ATLAS material (data/material_conversion_summary.csv, M01)")
MC = rd(f"{D}/material_conversion_summary.csv"); md(MC, {c: (lambda v: f"{v:.4f}") for c in MC.columns if MC[c].dtype.kind == "f" and c != "n_photons"})

h("## 10. Tests (last line of each log in logs/)")
tl = []
for f in sorted(glob.glob(f"{R}/logs/T*.log")):
    s = open(f).read().strip().splitlines(); v = [l for l in s if re.search(r"T\d+_(PASS|FAIL)|PASS|FAIL", l)]
    tl.append(dict(log=os.path.basename(f), result=(v[-1] if v else (s[-1] if s else "")).strip()[:90]))
md(pd.DataFrame(tl))
open(f"{T}/R02_results_summary.md", "w").write("\n".join(out)); print("R02: wrote tables/R02_results_summary.md and tables/R02_integration_failures.csv")
